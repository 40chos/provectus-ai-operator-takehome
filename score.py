"""Compares run-report.json against the supplied expected-seed-results.json.

Treats expected results as ground truth (never regenerated by the
application itself). Exits non-zero on any mismatch.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def _status_matches(expected: str, actual_report: dict) -> bool:
    if expected == actual_report["status"]:
        return True
    # R5's expected status is a single string covering two valid outcomes:
    # a successful save after exactly one retry, OR a failed save after
    # exhausting the retry. Map our richer internal states onto it.
    if expected == "draft-after-one-retry-or-failed":
        if actual_report["status"] == "draft" and actual_report["had_failure"]:
            return True
        if actual_report["status"] == "failed" and actual_report["had_failure"]:
            return True
    return False


def score(report_path: Path, expected_path: Path) -> bool:
    report = {r["request_id"]: r for r in json.loads(report_path.read_text())}
    expected = json.loads(expected_path.read_text())

    all_ok = True
    print(f"{'request':10} {'result':6} expected -> actual")
    for exp in expected:
        rid = exp["file_id"] if "file_id" in exp else exp["request_id"]
        actual = report.get(rid)
        if actual is None:
            print(f"{rid:10} {'FAIL':6} no result produced for this request")
            all_ok = False
            continue

        ok = True
        details = []

        if "status" in exp:
            status_ok = _status_matches(exp["status"], actual)
            ok &= status_ok
            details.append(f"status: expected={exp['status']!r} actual={actual['status']!r} {'OK' if status_ok else 'MISMATCH'}")

        if "new_drafts" in exp:
            drafts_ok = actual["new_drafts"] == exp["new_drafts"]
            ok &= drafts_ok
            details.append(f"new_drafts: expected={exp['new_drafts']} actual={actual['new_drafts']} {'OK' if drafts_ok else 'MISMATCH'}")

        if "max_new_drafts" in exp:
            drafts_ok = actual["new_drafts"] <= exp["max_new_drafts"]
            ok &= drafts_ok
            details.append(
                f"new_drafts<=max: expected<={exp['max_new_drafts']} actual={actual['new_drafts']} {'OK' if drafts_ok else 'MISMATCH'}"
            )

        if exp.get("failure_must_be_visible"):
            vis_ok = actual["had_failure"] is True
            ok &= vis_ok
            details.append(f"failure_must_be_visible: actual had_failure={actual['had_failure']} {'OK' if vis_ok else 'MISMATCH'}")

        print(f"{rid:10} {'PASS' if ok else 'FAIL':6} " + "; ".join(details))
        all_ok &= ok

    return all_ok


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--report", default="run-report.json")
    parser.add_argument(
        "--expected",
        default="../client-ai-starter-pack/tasks/computer-use/expected-seed-results.json",
    )
    args = parser.parse_args()

    ok = score(Path(args.report), Path(args.expected))
    print("\nRESULT:", "ALL PASS" if ok else "SOME FAILED")
    sys.exit(0 if ok else 1)
